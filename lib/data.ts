// Въпроси за дуел: смесица от куизовете на отключените за потребителя светове
export function getDuelQuestions(userLevel: number, count = 5): QuizQuestion[] {
  const unlockedWorldIds = WORLDS.filter((w) => userLevel >= w.requiredLevel).map((w) => w.id);
  let pool = LESSONS.filter((l) => unlockedWorldIds.includes(l.worldId)).flatMap((l) => l.quiz);
  if (pool.length < count) pool = LESSONS.flatMap((l) => l.quiz);
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}


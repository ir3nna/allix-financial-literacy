export type QuizQuestion = {
  question: string;
  options: string[];
  correct: number; // индекс на верния отговор
  explanation: string;
};

export type Interaction =
  | {
      type: "slider";
      prompt: string;
      min: number;
      max: number;
      step: number;
      unit: string;
      feedback: (value: number) => string;
    }
  | {
      type: "choice";
      prompt: string;
      options: { label: string; feedback: string; good: boolean }[];
    };

// Ниво на съдържанието по клас — едно съдържание, но математиката се представя
// според класа на ученика (проценти → сравнение на оферти → формули и прогресии).
export type GradeLevel = "A" | "B" | "V";

export const GRADE_LEVELS: { key: GradeLevel; label: string; grade: string; math: string }[] = [
  { key: "A", label: "Ниво А", grade: "VIII–IX клас", math: "Проценти и едностъпкови сметки" },
  { key: "B", label: "Ниво Б", grade: "X клас", math: "Многостъпкови сметки, сравнение на две оферти" },
  { key: "V", label: "Ниво В", grade: "XI клас", math: "Формули, прогресии, показателна функция" },
];

export const gradeLevelInfo = (key: GradeLevel) =>
  GRADE_LEVELS.find((l) => l.key === key) ?? GRADE_LEVELS[0];


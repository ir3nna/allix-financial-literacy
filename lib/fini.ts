export function finiReply(input: string, ctx: { name: string; level: number }): string {
  const q = input.toLowerCase();

  if (/(здравей|здрасти|хей|привет|добър ден|добро утро|ку-ку)/.test(q)) {
    return `Здравей, ${ctx.name}! Аз съм Фини 🦅 — твоят финансов орел. Питай ме за всичко около парите: инфлация, бюджет, лихви... или кажи „дай ми съвет“!`;
  }
  if (/(съвет|препоръч|идея)/.test(q)) {
    return `Ето един мъдър съвет от орела: ${randomFrom(DAILY_TIPS)}`;
  }
  if (/(благодаря|мерси|супер|страхотно|яко)/.test(q)) {
    return "Пак заповядай! Орлите винаги са насреща. 🦅 Още въпроси?";
  }
  if (/(кой си|коя си|какво си|какво можеш|помощ|какво умееш)/.test(q)) {
    return `Аз съм Фини — Финансовият орел на Allianz Academy! 🦅 Обяснявам финансови понятия просто и давам подсказки, когато закъсаш. В момента си ниво ${ctx.level} — питай ме как да стигнеш по-високо!`;
  }

  for (const entry of KNOWLEDGE) {
    if (entry.keywords.some((k) => q.includes(k))) return entry.answer;
  }
  return randomFrom(FALLBACKS);
}

